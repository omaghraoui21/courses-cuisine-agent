// Run: node tests/household.mjs. Transpile the pure reducer without a server or D1.
import ts from 'typescript';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const encode=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const compile=path=>ts.transpileModule(readFileSync(new URL(path,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const domainUrl=encode(compile('../lib/domain.ts'));
const source=compile('../lib/household.ts').replace("'./domain'",JSON.stringify(domainUrl)).replace("'zod'",JSON.stringify(pathToFileURL(require.resolve('zod')).href));
const {applyAction,actionSchema,monthlyForecast}=await import(encode(source));
const {emptyState}=await import(domainUrl);
const parse=(payload)=>actionSchema.parse({requestId:crypto.randomUUID(),...payload});
let state=emptyState();
const add=parse({action:'add_item',item:{name:'Café',quantity:2}});
state=applyAction(state,add,'add');
assert.equal(state.items.length,1);
assert.equal(applyAction(state,add,'add'),state,'retry is idempotent');
assert.throws(()=>applyAction(state,add,'different'),/autre action/);
assert.equal(monthlyForecast(state.items[0]),null,'no invented consumption');
const originalId=state.items[0].id;
state=applyAction(state,parse({action:'import_items',mode:'inventory',items:[{name:' café ',quantity:3}]}),'inventory');
assert.equal(state.items.length,1);
assert.equal(state.items[0].quantity,3,'inventory replaces rather than adds');
assert.equal(state.items[0].id,originalId);
state=applyAction(state,parse({action:'import_items',mode:'purchase',items:[{name:'Café',quantity:2}]}),'purchase');
assert.equal(state.items[0].quantity,5);
assert.throws(()=>applyAction(state,parse({action:'consume_item',id:originalId,quantity:6}),'overconsume'),/supérieure/);
state=applyAction(state,parse({action:'consume_item',id:originalId,quantity:5}),'consume');
assert.equal(state.items[0].level,'empty');
const last=state.events.at(-1).id;
assert.throws(()=>applyAction(state,parse({action:'undo_event',id:state.events[0].id}),'oldUndo'),/dernière/);
state=applyAction(state,parse({action:'undo_event',id:last}),'undo');
assert.equal(state.items[0].quantity,5);
assert.throws(()=>applyAction(state,parse({action:'undo_event',id:last}),'doubleUndo'),/dernière/);
assert.equal(actionSchema.safeParse({action:'clear_data',requestId:crypto.randomUUID(),confirmation:'yes'}).success,false);
assert.equal(actionSchema.safeParse({action:'add_item',requestId:crypto.randomUUID(),item:{name:'x',expiry:'2026-02-31'}}).success,false);
state=applyAction(state,parse({action:'clear_data',confirmation:'SUPPRIMER'}),'clear');
assert.equal(state.items.length,0);assert.equal(state.events.length,1);assert.equal(state.events[0].before,undefined);
console.log('Household reducer: 16 assertions passed.');
// Regression: incomplete OCR inventory must preserve confirmed household metadata.
let bathroom=applyAction(emptyState(),parse({action:'add_item',item:{name:'Shampooing',brand:'Habituel',quantity:2,unit:'flacon',category:'hygiene',location:'Salle de bain',monthlyUsage:2,expiry:'2027-01-01'}}),'shampoo');
bathroom=applyAction(bathroom,parse({action:'import_items',mode:'inventory',items:[{name:'Shampooing',quantity:1,expiry:null,monthlyUsage:null,location:null,category:null,unit:null,brand:null}]}),'ocr');
assert.equal(bathroom.items.length,1);
assert.equal(bathroom.items[0].quantity,1);
assert.equal(bathroom.items[0].category,'hygiene');
assert.equal(bathroom.items[0].location,'Salle de bain');
assert.equal(bathroom.items[0].monthlyUsage,2);
assert.equal(bathroom.items[0].expiry,'2027-01-01');
assert.equal(bathroom.items[0].brand,'Habituel');
assert.equal(bathroom.items[0].unit,'flacon');
for(const quantity of [undefined,null,'unknown'])assert.equal(actionSchema.safeParse({action:'import_items',requestId:crypto.randomUUID(),items:[{name:'Shampooing',quantity}]}).success,false,'unknown quantity is rejected');
bathroom=applyAction(bathroom,parse({action:'update_item',id:bathroom.items[0].id,patch:{expiry:null,monthlyUsage:null}}),'clearMetadata');
assert.equal(bathroom.items[0].expiry,null,'explicit user editing can clear expiry');
assert.equal(bathroom.items[0].monthlyUsage,null);
console.log('OCR metadata regression: 13 assertions passed.');
// Image hashes are durable and independent from per-request idempotency.
const hash='a'.repeat(64), differentHash='b'.repeat(64);
const photoPayload={action:'import_items',mode:'purchase',fingerprints:[hash],items:[{name:'Lait',quantity:2,unit:'litre'}]};
let photos=applyAction(emptyState(),parse(photoPayload),'photo1');
assert.deepEqual(photos.importFingerprints,[hash]);
assert.throws(()=>applyAction(photos,parse(photoPayload),'photo2'),/déjà été confirmée/);
assert.throws(()=>applyAction(photos,parse({...photoPayload,mode:'inventory'}),'photo3'),/déjà été confirmée/);
photos=applyAction(photos,parse({...photoPayload,fingerprints:[differentHash]}),'photo4');
assert.equal(photos.items[0].quantity,4,'different photo can represent a legitimate new purchase');
photos=applyAction(photos,parse({action:'undo_event',id:photos.events.at(-1).id}),'undoPhoto');
assert.deepEqual(photos.importFingerprints,[hash],'undo releases fingerprints of that import only');
photos=applyAction(photos,parse({...photoPayload,fingerprints:[differentHash]}),'reimport');
assert.equal(photos.items[0].quantity,4);
photos.requests=[];
assert.throws(()=>applyAction(photos,parse(photoPayload),'afterHistory'),/déjà été confirmée/,'duplicate protection survives request rotation');
assert.equal(actionSchema.safeParse({...photoPayload,requestId:crypto.randomUUID(),fingerprints:['not-a-hash']}).success,false);
const full={...emptyState(),importFingerprints:Array.from({length:2000},(_,i)=>i.toString(16).padStart(64,'0'))};
assert.throws(()=>applyAction(full,parse(photoPayload),'limit'),/2 000/);
photos=applyAction(photos,parse({action:'clear_data',confirmation:'SUPPRIMER'}),'clearPhoto');
assert.deepEqual(photos.importFingerprints,[]);
console.log('Photo duplication regression: 10 assertions passed.');
// Light consumption learning: explicit events, adequate span, manual priority.
const {calculateForecasts}=await import(encode(source));
let learning=applyAction(emptyState(),parse({action:'add_item',item:{name:'Gel douche',quantity:12,category:'hygiene'}}),'learnAdd','2026-01-01T00:00:00Z');
const itemId=learning.items[0].id;
const consume=(at,fingerprint)=>{learning=applyAction(learning,parse({action:'consume_item',id:itemId,quantity:1}),fingerprint,at);};
consume('2026-01-01T00:00:00Z','learn1');consume('2026-01-08T00:00:00Z','learn2');
assert.equal(calculateForecasts(learning,'2026-01-20T00:00:00Z').length,0);
consume('2026-01-15T00:00:00Z','learn3');
const observed=calculateForecasts(learning,'2026-01-20T00:00:00Z')[0];
assert.equal(observed.basis,'observed');assert.equal(observed.samples,3);assert.equal(observed.spanDays,14);
assert.equal(observed.monthly,2/14*30.4375);assert.equal(observed.annual,observed.monthly*12);
assert.equal(calculateForecasts(learning,'2026-01-10T00:00:00Z').length,0,'future observations excluded');
learning=applyAction(learning,parse({action:'undo_event',id:learning.events.at(-1).id}),'undoLearn');
assert.equal(learning.consumption.length,2);assert.equal(calculateForecasts(learning).length,0);
learning=applyAction(learning,parse({action:'update_item',id:itemId,patch:{monthlyUsage:2}}),'manualLearn');
assert.equal(calculateForecasts(learning)[0].basis,'declared');assert.equal(calculateForecasts(learning)[0].annual,24);
learning=applyAction(learning,parse({action:'update_item',id:itemId,patch:{unit:'ml',monthlyUsage:null}}),'unitLearn');
assert.equal(learning.consumption.length,0,'unit changes invalidate incompatible observations');
// Undoing an unrelated consumption must retain already confirmed image fingerprints.
let hashed=applyAction(emptyState(),parse(photoPayload),'fingerprintPurchase');
hashed=applyAction(hashed,parse({action:'consume_item',id:hashed.items[0].id,quantity:1}),'fingerprintConsume');
hashed=applyAction(hashed,parse({action:'undo_event',id:hashed.events.at(-1).id}),'fingerprintUndo');
assert.deepEqual(hashed.importFingerprints,[hash]);
assert.throws(()=>applyAction(hashed,parse(photoPayload),'duplicateAfterUndo'),/déjà été confirmée/);
console.log('Consumption learning and undo fingerprints: 14 assertions passed.');
// Adoption shortcuts change estimates, not measured consumption; needs are idempotent.
let simple=applyAction(emptyState(),parse({action:'add_item',item:{name:'Gel douche',quantity:3,unit:'flacon',category:'hygiene',monthlyUsage:6}}),'simpleAdd');
const simpleId=simple.items[0].id;
simple=applyAction(simple,parse({action:'mark_level',id:simpleId,level:'low'}),'simpleLow');
assert.equal(simple.items[0].quantity,3,'low does not invent a quantity consumed');
assert.equal(simple.items[0].level,'low');
assert.equal(simple.consumption.length,0,'level changes do not train consumption');
assert.equal(simple.shopping.length,1);
simple=applyAction(simple,parse({action:'mark_level',id:simpleId,level:'low'}),'simpleLowAgain');
assert.equal(simple.shopping.length,1,'repeated low declaration does not duplicate a need');
simple=applyAction(simple,parse({action:'add_shopping',item:{name:' GEL  DOUCHE ',quantity:2,unit:'FLACON',retailer:'MG'}}),'simpleShopping');
assert.equal(simple.shopping.length,1,'normalization merges a manual entry with the generic need');
assert.equal(simple.shopping[0].quantity,2,'merge takes max instead of sum');
assert.equal(simple.shopping[0].retailer,'MG');
simple=applyAction(simple,parse({action:'add_shopping',item:{name:'Gel douche',quantity:1,unit:'flacon'}}),'simpleShoppingAgain');
assert.equal(simple.shopping[0].quantity,2);
assert.equal(simple.shopping[0].retailer,'MG','generic addition preserves store preference');
simple=applyAction(simple,parse({action:'mark_level',id:simpleId,level:'empty'}),'simpleEmpty');
assert.equal(simple.items[0].quantity,0);
assert.equal(simple.consumption.length,0);
simple=applyAction(simple,parse({action:'suggest_shopping',days:30}),'simpleSuggest','2026-10-18T00:00:00Z');
assert.equal(simple.shopping.length,1);
assert.equal(simple.shopping[0].quantity,6,'forecast suggests declared horizon need');
simple=applyAction(simple,parse({action:'suggest_shopping',days:30}),'simpleSuggestAgain','2026-10-18T00:00:00Z');
assert.equal(simple.shopping[0].quantity,6,'repeat suggestion does not add quantities');
assert.equal(simple.items[0].quantity,0,'suggestion does not count as purchase');
simple=applyAction(simple,parse({action:'mark_level',id:simpleId,level:'sufficient'}),'simpleSufficient');
assert.equal(simple.items[0].quantity,0,'sufficient does not invent exact stock');
assert.equal(simple.shopping.length,1,'sufficient does not silently remove explicit shopping');
assert.equal(actionSchema.safeParse({requestId:crypto.randomUUID(),action:'suggest_shopping',days:365}).success,false);
let weekly=applyAction(emptyState(),parse({action:'add_item',item:{name:'Café',quantity:1,monthlyUsage:4}}),'weeklyAdd');
weekly=applyAction(weekly,parse({action:'suggest_shopping',days:7}),'weeklySuggest');
assert.equal(weekly.shopping.length,0,'stock covering the next week needs no purchase');
weekly=applyAction(weekly,parse({action:'mark_level',id:weekly.items[0].id,level:'empty'}),'weeklyEmpty');
const undoEmpty=weekly.events.at(-1).id;
weekly=applyAction(weekly,parse({action:'undo_event',id:undoEmpty}),'weeklyUndo');
assert.equal(weekly.items[0].quantity,1);
assert.equal(weekly.shopping.length,0,'undo atomically restores both stock and list');
console.log('Simple levels and smart shopping: 22 assertions passed.');
